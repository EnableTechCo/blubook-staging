alter table public.opportunity_sources enable row level security;
alter table public.forecast_categories enable row level security;
alter table public.sales_opportunities enable row level security;
alter table public.sales_opportunity_events enable row level security;

create policy opportunity_sources_select_active on public.opportunity_sources
  for select to authenticated
  using (active);

create policy forecast_categories_select_active on public.forecast_categories
  for select to authenticated
  using (active);

create policy sales_opportunities_select_own on public.sales_opportunities
  for select to authenticated
  using (client_id = public.current_client_id());

create policy sales_opportunities_insert_own on public.sales_opportunities
  for insert to authenticated
  with check (client_id = public.current_client_id());

create policy sales_opportunities_update_own on public.sales_opportunities
  for update to authenticated
  using (client_id = public.current_client_id())
  with check (client_id = public.current_client_id());

create policy sales_opportunities_delete_pre_booking on public.sales_opportunities
  for delete to authenticated
  using (
    client_id = public.current_client_id()
    and booked_at is null
    and invoice_number is null
    and payment_status is null
  );

create policy sales_opportunity_events_select_own on public.sales_opportunity_events
  for select to authenticated
  using (client_id = public.current_client_id());

grant select on public.opportunity_sources to authenticated;
grant select on public.forecast_categories to authenticated;

grant select, insert, delete on public.sales_opportunities to authenticated;
grant update (
  opportunity_source,
  opportunity_name,
  forecast_category,
  revenue,
  fiscal_year,
  fiscal_quarter,
  fiscal_week
) on public.sales_opportunities to authenticated;
grant select on public.sales_opportunity_events to authenticated;

grant all on public.opportunity_sources to service_role;
grant all on public.forecast_categories to service_role;
grant all on public.sales_opportunities to service_role;
grant all on public.sales_opportunity_events to service_role;
grant usage, select on sequence public.sales_opportunity_reference_seq to service_role;

revoke execute on function public.opportunity_actor_type() from public;
revoke execute on function public.prepare_sales_opportunity() from public;
revoke execute on function public.guard_sales_opportunity_lifecycle() from public;
revoke execute on function public.guard_sales_opportunity_delete() from public;
revoke execute on function public.log_sales_opportunity_event() from public;
