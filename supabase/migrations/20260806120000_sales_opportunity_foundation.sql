create or replace function public.log_sales_opportunity_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := (select auth.uid());
  v_actor_type public.opportunity_actor_type := public.opportunity_actor_type();
begin
  if tg_op = 'INSERT' then
    insert into public.sales_opportunity_events (
      opportunity_id, client_id, deal_reference, event_type, actor_id, actor_type, details
    ) values (
      new.id,
      new.client_id,
      new.deal_reference,
      'created',
      v_actor_id,
      v_actor_type,
      jsonb_build_object(
        'opportunity_source', new.opportunity_source,
        'opportunity_name', new.opportunity_name,
        'forecast_category', new.forecast_category,
        'revenue', new.revenue,
        'currency', new.currency,
        'fiscal_year', new.fiscal_year,
        'fiscal_quarter', new.fiscal_quarter,
        'fiscal_week', new.fiscal_week
      )
    );
    return new;
  end if;

  if tg_op = 'DELETE' then
    insert into public.sales_opportunity_events (
      opportunity_id, client_id, deal_reference, event_type, actor_id, actor_type, details
    ) values (
      old.id,
      old.client_id,
      old.deal_reference,
      'deleted',
      v_actor_id,
      v_actor_type,
      jsonb_build_object('opportunity_name', old.opportunity_name)
    );
    return old;
  end if;

  if new.forecast_category is distinct from old.forecast_category then
    insert into public.sales_opportunity_events (
      opportunity_id, client_id, deal_reference, event_type, actor_id, actor_type, details
    ) values (
      new.id, new.client_id, new.deal_reference, 'category_changed', v_actor_id, v_actor_type,
      jsonb_build_object('before', old.forecast_category, 'after', new.forecast_category)
    );
  end if;

  if new.booked_at is distinct from old.booked_at and new.booked_at is not null then
    insert into public.sales_opportunity_events (
      opportunity_id, client_id, deal_reference, event_type, actor_id, actor_type, details
    ) values (
      new.id, new.client_id, new.deal_reference, 'booked', v_actor_id, v_actor_type,
      jsonb_build_object('booked_at', new.booked_at)
    );
  end if;

  if new.invoice_number is distinct from old.invoice_number then
    insert into public.sales_opportunity_events (
      opportunity_id, client_id, deal_reference, event_type, actor_id, actor_type, details
    ) values (
      new.id, new.client_id, new.deal_reference, 'invoice_updated', v_actor_id, v_actor_type,
      jsonb_build_object('before', old.invoice_number, 'after', new.invoice_number)
    );
  end if;

  if new.payment_status is distinct from old.payment_status
     or new.paid_at is distinct from old.paid_at then
    insert into public.sales_opportunity_events (
      opportunity_id, client_id, deal_reference, event_type, actor_id, actor_type, details
    ) values (
      new.id, new.client_id, new.deal_reference, 'payment_changed', v_actor_id, v_actor_type,
      jsonb_build_object(
        'before', jsonb_build_object('status', old.payment_status, 'paid_at', old.paid_at),
        'after', jsonb_build_object('status', new.payment_status, 'paid_at', new.paid_at)
      )
    );
  end if;

  if new.opportunity_source is distinct from old.opportunity_source
     or new.opportunity_name is distinct from old.opportunity_name
     or new.revenue is distinct from old.revenue
     or new.fiscal_year is distinct from old.fiscal_year
     or new.fiscal_quarter is distinct from old.fiscal_quarter
     or new.fiscal_week is distinct from old.fiscal_week then
    insert into public.sales_opportunity_events (
      opportunity_id, client_id, deal_reference, event_type, actor_id, actor_type, details
    ) values (
      new.id,
      new.client_id,
      new.deal_reference,
      'updated',
      v_actor_id,
      v_actor_type,
      jsonb_build_object(
        'before', jsonb_build_object(
          'opportunity_source', old.opportunity_source,
          'opportunity_name', old.opportunity_name,
          'revenue', old.revenue,
          'fiscal_year', old.fiscal_year,
          'fiscal_quarter', old.fiscal_quarter,
          'fiscal_week', old.fiscal_week
        ),
        'after', jsonb_build_object(
          'opportunity_source', new.opportunity_source,
          'opportunity_name', new.opportunity_name,
          'revenue', new.revenue,
          'fiscal_year', new.fiscal_year,
          'fiscal_quarter', new.fiscal_quarter,
          'fiscal_week', new.fiscal_week
        )
      )
    );
  end if;

  return new;
end;
$$;

create trigger sales_opportunities_log_event
  after insert or update on public.sales_opportunities
  for each row execute function public.log_sales_opportunity_event();

create trigger sales_opportunities_log_delete
