create table public.sales_opportunity_events (
  id               uuid primary key default gen_random_uuid(),
  -- Set null on a permitted pre-booking delete so the audit event survives.
  opportunity_id   uuid references public.sales_opportunities (id) on delete set null,
  client_id        uuid not null references public.clients (id) on delete cascade,
  deal_reference   text not null,
  event_type       public.opportunity_event_type not null,
  actor_id         uuid references public.profiles (id) on delete set null,
  actor_type       public.opportunity_actor_type not null,
  details          jsonb not null default '{}'::jsonb,
  created_at       timestamptz not null default now()
);

comment on table public.sales_opportunity_events is
  'Append-only audit history for material opportunity and booking lifecycle changes.';

create index sales_opportunity_events_opportunity_id_idx
  on public.sales_opportunity_events (opportunity_id, created_at desc);
create index sales_opportunity_events_client_id_idx
  on public.sales_opportunity_events (client_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Defaults, immutability and lifecycle guards
-- ---------------------------------------------------------------------------

create or replace function public.opportunity_actor_type()
returns public.opportunity_actor_type
language sql
stable
security definer
set search_path = ''
as $$
  select case public.current_user_type()
    when 'client' then 'client'::public.opportunity_actor_type
    when 'service_provider' then 'service_provider'::public.opportunity_actor_type
    when 'staff' then 'staff'::public.opportunity_actor_type
    else 'system'::public.opportunity_actor_type
  end;
$$;

create or replace function public.prepare_sales_opportunity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_client_id uuid;
  v_sequence bigint;
  v_year text;
begin
  if v_uid is not null then
    if public.current_user_type() is distinct from 'client'::public.user_type then
      raise exception 'Only client users may create sales opportunities';
    end if;

    v_client_id := public.current_client_id();
    if v_client_id is null then
      raise exception 'No client account is linked to the current profile';
    end if;
    if new.client_id is null then
      new.client_id := v_client_id;
    elsif new.client_id is distinct from v_client_id then
      raise exception 'Cannot create an opportunity for another client';
    end if;

    if nullif(btrim(new.deal_reference), '') is not null then
      raise exception 'Deal ID is generated by the system';
    end if;
    if new.invoice_number is not null
       or new.payment_status is not null
       or new.booked_at is not null
       or new.paid_at is not null then
      raise exception 'Invoice, booking and payment fields are system managed';
    end if;
    if not exists (
      select 1 from public.opportunity_sources
      where code = new.opportunity_source and active
    ) then
      raise exception 'Choose an active opportunity source';
    end if;
    if not exists (
      select 1 from public.forecast_categories
      where code = new.forecast_category and active
    ) then
      raise exception 'Choose an active forecast category';
    end if;

    -- Defaults are evaluated before BEFORE INSERT triggers. Reassert all
    -- system-owned identity fields so crafted API payloads cannot choose them.
    new.id := gen_random_uuid();
    new.created_by := v_uid;
    new.currency := 'ZAR';
    new.created_at := now();
    new.updated_at := now();
  end if;

  if nullif(btrim(new.deal_reference), '') is null then
    v_sequence := nextval('public.sales_opportunity_reference_seq');
    v_year := to_char(timezone('Africa/Johannesburg', statement_timestamp()), 'YYYY');
    new.deal_reference := 'BLB-' || v_year || '-' || lpad(v_sequence::text, 6, '0');
  end if;

  new.opportunity_name := btrim(new.opportunity_name);
  if new.invoice_number is not null then
    new.invoice_number := btrim(new.invoice_number);
  end if;
  return new;
end;
$$;

create trigger sales_opportunities_prepare
  before insert on public.sales_opportunities
  for each row execute function public.prepare_sales_opportunity();

create or replace function public.guard_sales_opportunity_lifecycle()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.id is distinct from old.id
     or new.client_id is distinct from old.client_id
     or new.deal_reference is distinct from old.deal_reference
     or new.currency is distinct from old.currency
     or new.created_by is distinct from old.created_by
     or new.created_at is distinct from old.created_at then
    raise exception 'Opportunity identity fields are immutable';
  end if;

  if old.booked_at is not null and new.booked_at is null then
    raise exception 'The permanent booking timestamp cannot be cleared';
  end if;

  if new.opportunity_source is distinct from old.opportunity_source and not exists (
    select 1 from public.opportunity_sources
    where code = new.opportunity_source and active
  ) then
    raise exception 'Choose an active opportunity source';
  end if;
  if new.forecast_category is distinct from old.forecast_category and not exists (
    select 1 from public.forecast_categories
    where code = new.forecast_category and active
  ) then
    raise exception 'Choose an active forecast category';
  end if;

  new.opportunity_name := btrim(new.opportunity_name);
  if new.invoice_number is not null then
    new.invoice_number := btrim(new.invoice_number);
  end if;
  return new;
end;
$$;

create trigger sales_opportunities_guard_lifecycle
  before update on public.sales_opportunities
  for each row execute function public.guard_sales_opportunity_lifecycle();

create or replace function public.guard_sales_opportunity_delete()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.booked_at is not null
     or old.invoice_number is not null
     or old.payment_status is not null then
    raise exception 'Booked, invoiced or payment-tracked opportunities cannot be deleted';
  end if;
  return old;
end;
$$;

create trigger sales_opportunities_guard_delete
  before delete on public.sales_opportunities
  for each row execute function public.guard_sales_opportunity_delete();

create trigger sales_opportunities_set_updated_at
  before update on public.sales_opportunities
  for each row execute function public.set_updated_at();

