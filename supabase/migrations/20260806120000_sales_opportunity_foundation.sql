-- Sales opportunity foundation
--
-- Establishes the client-owned sales pipeline source of truth used by the
-- future Pipeline and Bookings views. An opportunity may exist without a PO;
-- the PO relationship arrives in a later migration. Providers and staff do
-- not receive table access. Future provider invoice/payment actions must use
-- narrow SECURITY DEFINER functions instead of broad table grants.

-- ---------------------------------------------------------------------------
-- Controlled reference data and lifecycle enums
-- ---------------------------------------------------------------------------

create type public.opportunity_payment_status as enum ('unpaid', 'paid');

create type public.opportunity_event_type as enum (
  'created',
  'updated',
  'category_changed',
  'booked',
  'invoice_updated',
  'payment_changed',
  'deleted'
);

create type public.opportunity_actor_type as enum (
  'client',
  'service_provider',
  'staff',
  'system'
);

create table public.opportunity_sources (
  code          text primary key check (code ~ '^[a-z][a-z0-9_]*$'),
  name          text not null unique,
  description   text,
  display_order integer not null default 0,
  active        boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

comment on table public.opportunity_sources is
  'Controlled acquisition sources available to client sales opportunities.';

create table public.forecast_categories (
  code          text primary key check (code ~ '^[a-z][a-z0-9_]*$'),
