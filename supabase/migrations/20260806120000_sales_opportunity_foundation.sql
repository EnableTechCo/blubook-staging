-- ---------------------------------------------------------------------------
-- Sales opportunities
-- ---------------------------------------------------------------------------

create sequence public.sales_opportunity_reference_seq;

create table public.sales_opportunities (
  id                    uuid primary key default gen_random_uuid(),
  client_id             uuid not null default public.current_client_id() references public.clients (id) on delete cascade,
  deal_reference        text not null default '' unique,
  opportunity_source    text not null references public.opportunity_sources (code) on update restrict on delete restrict,
  opportunity_name      text not null check (btrim(opportunity_name) <> ''),
  forecast_category     text not null default 'open' references public.forecast_categories (code) on update restrict on delete restrict,
  revenue               numeric(14, 2) not null default 0 check (revenue >= 0),
  currency              text not null default 'ZAR' check (currency = 'ZAR'),
  -- Expected-payment period. Early opportunities may omit all three. A client
  -- may know the year, then quarter, before it knows the exact quarter week.
  fiscal_year           smallint check (fiscal_year between 2000 and 2200),
  fiscal_quarter        smallint check (fiscal_quarter between 1 and 4),
  fiscal_week           smallint check (fiscal_week between 1 and 13),
  invoice_number        text check (invoice_number is null or btrim(invoice_number) <> ''),
  payment_status        public.opportunity_payment_status,
  booked_at             timestamptz,
  paid_at               timestamptz,
  created_by            uuid references public.profiles (id) on delete set null,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  constraint sales_opportunities_fiscal_hierarchy check (
    (fiscal_year is not null or (fiscal_quarter is null and fiscal_week is null))
    and (fiscal_quarter is not null or fiscal_week is null)
  ),
  constraint sales_opportunities_payment_requires_booking check (
    payment_status is null or booked_at is not null
  ),
  constraint sales_opportunities_paid_timestamp check (
    (payment_status = 'paid' and paid_at is not null)
    or (payment_status is distinct from 'paid' and paid_at is null)
  )
);

comment on table public.sales_opportunities is
  'Client-owned sales opportunities. Pipeline and Bookings are views of this same row; opportunities may exist without a PO.';
comment on column public.sales_opportunities.deal_reference is
  'Generated immutable identifier in BLB-YYYY-NNNNNN format.';
comment on column public.sales_opportunities.fiscal_week is
  'Expected-payment week within the selected fiscal quarter (1–13).';
comment on column public.sales_opportunities.booked_at is
  'Permanent timestamp of the first completed linked PO; it may never be cleared.';
comment on column public.sales_opportunities.revenue is
  'Client-entered expected revenue in ZAR. VAT inclusion semantics remain a product reporting decision.';

create index sales_opportunities_client_id_idx
  on public.sales_opportunities (client_id);
create index sales_opportunities_client_category_idx
  on public.sales_opportunities (client_id, forecast_category);
create index sales_opportunities_client_period_idx
  on public.sales_opportunities (client_id, fiscal_year, fiscal_quarter, fiscal_week);
create index sales_opportunities_booked_at_idx
  on public.sales_opportunities (booked_at)
  where booked_at is not null;
create unique index sales_opportunities_client_invoice_unique_idx
  on public.sales_opportunities (client_id, lower(invoice_number))
  where invoice_number is not null;

-- ---------------------------------------------------------------------------
